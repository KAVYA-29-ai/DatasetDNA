def render_categorical(
    categorical: dict[str, Any],
) -> None:
    """Render categorical analysis."""

    console.print()

    if not categorical:
        console.print(
            Panel(
                "No categorical columns detected.",
                title="Categorical Analysis",
            )
        )
        return

    table = Table(
        title="Categorical Analysis",
        show_header=True,
        header_style="bold cyan",
    )

    table.add_column("Column")
    table.add_column("Unique Values")
    table.add_column("Top Categories")

    for column, result in categorical.items():

        categories = result["categories"]

        sorted_categories = sorted(
            categories.items(),
            key=lambda item: item[1]["count"],
            reverse=True,
        )

        top_categories = sorted_categories[:5]

        category_text = "\n".join(
            f"{category}: "
            f"{details['count']} "
            f"({details['percentage']}%)"
            for category, details in top_categories
        )

        table.add_row(
            column,
            str(result["unique_count"]),
            category_text if category_text else "No values",
        )

    console.print(table)


