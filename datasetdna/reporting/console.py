def render_correlations(
    correlations: dict[str, Any],
) -> None:
    """Render numerical correlations and categorical associations."""

    numeric_correlations = correlations.get(
        "numeric",
        [],
    )

    console.print()

    if numeric_correlations:

        table = Table(
            title="Numerical Correlations",
            show_header=True,
            header_style="bold cyan",
        )

        table.add_column("Column 1")
        table.add_column("Column 2")
        table.add_column("Pearson")

        for result in numeric_correlations:
            table.add_row(
                result["column_1"],
                result["column_2"],
                str(result["pearson"]),
            )

        console.print(table)

    else:
        console.print(
            Panel(
                "No numerical column pairs available.",
                title="Numerical Correlations",
            )
        )

    categorical_correlations = correlations.get(
        "categorical",
        [],
    )

    if categorical_correlations:

        console.print()

        table = Table(
            title="Categorical Associations",
            show_header=True,
            header_style="bold cyan",
        )

        table.add_column("Column 1")
        table.add_column("Column 2")
        table.add_column("Cramer's V")

        for result in categorical_correlations:
            table.add_row(
                result["column_1"],
                result["column_2"],
                str(result["cramers_v"]),
            )

        console.print(table)


def render_target(
    target: dict[str, Any],
) -> None:
    """Render target-column analysis."""

    table = Table(
        title="Target Analysis",
        show_header=True,
        header_style="bold cyan",
    )

    table.add_column("Metric")
    table.add_column("Value")

    if not target["provided"]:

        table.add_row(
            "Target",
            "Not provided",
        )

    elif "error" in target:

        table.add_row(
            "Target",
            target["column"],
        )

        table.add_row(
            "Status",
            target["error"],
        )

    elif target.get("type") == "empty":

        table.add_row(
            "Target",
            target["column"],
        )

        table.add_row(
            "Status",
            "Target contains no non-null values.",
        )

    else:

        table.add_row(
            "Target",
            target["column"],
        )

        table.add_row(
            "Type",
            target["type"],
        )

        table.add_row(
            "Classes",
            str(target["class_count"]),
        )

        imbalance_ratio = target["imbalance_ratio"]

        if imbalance_ratio is not None:
            table.add_row(
                "Imbalance Ratio",
                f"{imbalance_ratio}:1",
            )
        else:
            table.add_row(
                "Imbalance Ratio",
                "N/A",
            )

        distribution = target["class_distribution"]

        for category, details in distribution.items():
            table.add_row(
                f"Class: {category}",
                f'{details["count"]} '
                f'({details["percentage"]}%)',
            )

    console.print()
    console.print(table)


def render_completion() -> None:
    """Render successful completion message."""

    console.print()

    console.print(
        Panel(
            "[bold green]✓ DatasetDNA analysis "
            "completed successfully.[/bold green]",
            border_style="green",
        )
    )

    console.print()


def render_report(
    results: dict[str, Any],
    health: dict[str, Any],
) -> None:
    """
    Render the complete DatasetDNA console report.

    This function only renders data. It does not perform
    profiling or scoring.
    """

    render_header()

    render_health_score(health)

    render_health_findings(health)

    render_overview(
        results["overview"],
        results["missing"],
        results["duplicates"],
    )

    render_schema(
        results["schema"],
    )

    render_missing(
        results["missing"],
    )

    render_cardinality(
        results["cardinality"],
    )

    render_numerical(
        results["numerical"],
    )

    render_categorical(
        results["categorical"],
    )

    render_outliers(
        results["outliers"],
    )

    render_correlations(
        results["correlations"],
    )

    render_target(
        results["target"],
    )

    render_completion()