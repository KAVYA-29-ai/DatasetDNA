from typing import Any

from rich.console import Console
from rich.panel import Panel
from rich.table import Table


console = Console()


def _severity_display(severity: str) -> str:
    """Format issue severity for Rich output."""

    if severity == "severe":
        return "[bold red]SEVERE[/bold red]"

    if severity == "high":
        return "[red]HIGH[/red]"

    if severity == "medium":
        return "[yellow]MEDIUM[/yellow]"

    return "[dim]LOW[/dim]"


def _score_style(score: int) -> tuple[str, str]:
    """Return score style and status icon."""

    if score >= 90:
        return "bold green", "🟢"

    if score >= 75:
        return "bold yellow", "🟡"

    if score >= 60:
        return "bold yellow", "🟠"

    return "bold red", "🔴"


def render_header() -> None:
    """Render DatasetDNA header."""

    console.print()

    console.print(
        Panel.fit(
            "[bold cyan]🧬 DatasetDNA[/bold cyan]\n"
            "[bold white]Dataset Health Report[/bold white]",
            border_style="cyan",
        )
    )


def render_health_score(health: dict[str, Any]) -> None:
    """Render overall dataset health score."""

    score = int(health["score"])
    grade = health["grade"]
    issue_count = health["issue_count"]

    score_style, status_icon = _score_style(score)

    content = (
        f"{status_icon} [bold white]Health Score[/bold white]\n\n"
        f"[{score_style}]{score} / 100[/{score_style}]\n"
        f"[bold white]{grade}[/bold white]\n\n"
        f"[dim]{issue_count} issue(s) detected[/dim]"
    )

    console.print()

    console.print(
        Panel(
            content,
            title="🧬 Dataset Health",
            border_style="cyan",
            expand=False,
        )
    )


def render_health_findings(
    health: dict[str, Any],
) -> None:
    """Render health findings generated by the scoring layer."""

    issues = health.get("issues", [])

    console.print()

    if not issues:
        console.print(
            Panel(
                "[bold green]✓ No significant "
                "data-quality issues detected.[/bold green]",
                title="Health Findings",
                border_style="green",
            )
        )
        return

    table = Table(
        title="Health Findings",
        show_header=True,
        header_style="bold cyan",
    )

    table.add_column("Severity")
    table.add_column("Issue")
    table.add_column("Details")

    for issue in issues:

        severity = issue.get("severity", "low")

        details = ""

        if issue["type"] == "missing":
            details = (
                f"Column: {issue['column']} | "
                f"Missing: {issue['value']}%"
            )

        elif issue["type"] == "duplicates":
            details = (
                f"Duplicate rows: "
                f"{issue['value']}%"
            )

        elif issue["type"] == "outliers":
            details = (
                f"Column: {issue['column']} | "
                f"Outliers: {issue['value']}%"
            )

        elif issue["type"] == "correlation":
            columns = issue["columns"]

            details = (
                f"{columns[0]} ↔ {columns[1]} | "
                f"|r| = {issue['value']}"
            )

        elif issue["type"] == "target_imbalance":
            details = (
                f"Imbalance ratio: "
                f"{issue['value']}:1"
            )

        table.add_row(
            _severity_display(severity),
            issue["message"],
            details,
        )

    console.print(table)


